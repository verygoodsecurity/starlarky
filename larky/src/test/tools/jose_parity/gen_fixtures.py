"""Generate vendor_tests/jose/parity_fixtures.star from python-jose and joserfc.

Larky's jose is ported from python-jose's master branch at commit 8572088b
(see vendor/jose/__init__.star). The expected values here come from that
commit, run with the same inputs. joserfc supplies what python-jose does not
have: A*GCMKW, and "zip": "DEF" written as raw DEFLATE (RFC 7516), as other
libraries write it. keys/ holds a test-only RSA key, not a secret, made by
make_keys.sh (see keys/README.md).

Run from the repository root:

    uv run --no-project \
        --with "python-jose[pycryptodome] @ git+https://github.com/mpdavis/python-jose@8572088b76f7c0d31068f38aeca0d4273ae8bc8f" \
        --with joserfc==1.7.5 python -I \
        larky/src/test/tools/jose_parity/gen_fixtures.py \
        larky/src/test/tools/jose_parity/keys \
        larky/src/test/resources/vendor_tests/jose/parity_fixtures.star
"""
import base64
import sys
import zlib
from importlib.metadata import version
from pathlib import Path

from jose import jwe, jwk, jws
from joserfc import jwe as rfc_jwe
from joserfc.jwk import OctKey
from joserfc.jwe import JWERegistry

PLAINTEXT = b"hello" * 20
K16 = b"0123456789abcdef"
K24 = K16 + K16[:8]
K32 = K16 * 2
GCMKW = [("A128GCMKW", K16), ("A192GCMKW", K24), ("A256GCMKW", K32)]


def b64u(data: bytes) -> str:
    return base64.urlsafe_b64encode(data).rstrip(b"=").decode()


def main(keys: Path, out: Path) -> None:
    priv = (keys / "rsa.pem").read_text()
    pub = (keys / "rsa.pub.pem").read_text()

    # python-jose writes zlib (RFC 1950) data for "DEF".
    zip_token = jwe.encrypt(PLAINTEXT, K16, algorithm="dir", encryption="A128GCM", zip="DEF")
    assert jwe.decrypt(zip_token, K16) == PLAINTEXT

    # joserfc writes raw DEFLATE (RFC 1951).
    registry = JWERegistry(algorithms=["dir", "A128GCM", "A256CBC-HS512"] + [a for a, _ in GCMKW] + ["DEF"])
    raw_zip_token = rfc_jwe.encrypt_compact(
        {"alg": "dir", "enc": "A128GCM", "zip": "DEF"}, PLAINTEXT, OctKey.import_key(K16),
        registry=registry)
    ciphertext = rfc_jwe.decrypt_compact(raw_zip_token, OctKey.import_key(K16), registry=registry)
    assert ciphertext.plaintext == PLAINTEXT

    gcmkw_tokens = []
    for alg, key in GCMKW:
        for enc in ["A128GCM", "A256CBC-HS512"]:
            token = rfc_jwe.encrypt_compact({"alg": alg, "enc": enc}, PLAINTEXT,
                                            OctKey.import_key(key), registry=registry)
            assert rfc_jwe.decrypt_compact(token, OctKey.import_key(key),
                                           registry=registry).plaintext == PLAINTEXT
            gcmkw_tokens.append((alg, enc, token))

    oct_jwk = {"kty": "oct", "k": b64u(b"secret")}
    hs256_token = jws.sign(b"payload", oct_jwk, algorithm="HS256")
    pkcs1_public = jwk.construct(pub, "RS256").to_pem(pem_format="PKCS1").decode()

    lines = [
        "# Generated by larky/src/test/tools/jose_parity/gen_fixtures.py; do not edit.",
        "# python-jose %s (git 8572088b), joserfc %s." % (version("python-jose"), version("joserfc")),
        "",
        "PLAINTEXT = %r" % PLAINTEXT,
        "K16 = %r" % K16,
        "K24 = %r" % K24,
        "K32 = %r" % K32,
        "# Test-only key from larky/src/test/tools/jose_parity/keys; not a secret",
        "# (see keys/README.md there).",
        "# https://verygoodsecurity.atlassian.net/browse/SI-203",
        "# nosemgrep: secrets.misc.generic_private_key.generic_private_key",
        "RSA_PRIVATE_PEM = %r" % priv,
        "RSA_PUBLIC_PEM = %r" % pub,
        "",
        "# python-jose: jwe.encrypt(PLAINTEXT, K16, algorithm='dir', encryption='A128GCM', zip='DEF')",
        "PYJOSE_ZIP_TOKEN = %r" % zip_token.decode(),
        "# joserfc: the same, with raw DEFLATE",
        "JOSERFC_ZIP_TOKEN = %r" % raw_zip_token,
        "# joserfc: (alg, enc, token) for each A*GCMKW with key K16/K24/K32",
        "JOSERFC_GCMKW_TOKENS = %r" % (gcmkw_tokens,),
        "# python-jose: jws.sign(b'payload', {'kty': 'oct', 'k': b64u(b'secret')}, algorithm='HS256')",
        "PYJOSE_HS256_JWK_TOKEN = %r" % hs256_token,
        "# python-jose: jwk.construct(RSA_PUBLIC_PEM, 'RS256').to_pem(pem_format='PKCS1')",
        "PYJOSE_RSA_PUBLIC_PKCS1 = %r" % pkcs1_public,
        "",
    ]
    out.write_text("\n".join(lines).replace("'", '"'))


if __name__ == "__main__":
    main(Path(sys.argv[1]), Path(sys.argv[2]))
