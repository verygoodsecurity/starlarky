"""Generate vendor_tests/jose/ecdh_es_fixtures.star from a reference JOSE library.

Run from the repository root:

    uv run --no-project --with joserfc==1.7.5 python -I \
        larky/src/test/tools/x25519_ecdh_es/gen_jwe_fixtures.py \
        larky/src/test/tools/x25519_ecdh_es/keys \
        larky/src/test/resources/vendor_tests/jose/ecdh_es_fixtures.star

Every token is encrypted by joserfc to keys made by OpenSSL (make_keys.sh) and
decrypted again by joserfc before it is written. The expected Concat KDF
outputs are computed with `cryptography`'s ConcatKDFHash, an implementation
independent of both joserfc and Larky.
"""
import base64
import json
import sys
from importlib.metadata import version
from pathlib import Path

from cryptography.hazmat.primitives import hashes
from cryptography.hazmat.primitives.asymmetric.x25519 import X25519PrivateKey, X25519PublicKey
from cryptography.hazmat.primitives.kdf.concatkdf import ConcatKDFHash
from joserfc import jwe
from joserfc.jwk import ECKey, OKPKey
from joserfc.jwe import JWERegistry

PLAINTEXT = b'{"card":"4111111111111111","exp":"12/30","cvv":"123"}'

ALGS = ["ECDH-ES", "ECDH-ES+A128KW", "ECDH-ES+A192KW", "ECDH-ES+A256KW"]
ENCS = ["A128GCM", "A192GCM", "A256GCM"]
REGISTRY = JWERegistry(algorithms=ALGS + ENCS)


def b64u(data: bytes) -> str:
    return base64.urlsafe_b64encode(data).rstrip(b"=").decode()


def concat_kdf(z: bytes, alg_id: str, apu: bytes, apv: bytes, keydatalen: int) -> bytes:
    def lp(b: bytes) -> bytes:
        return len(b).to_bytes(4, "big") + b

    other = lp(alg_id.encode()) + lp(apu) + lp(apv) + keydatalen.to_bytes(4, "big")
    return ConcatKDFHash(hashes.SHA256(), keydatalen // 8, otherinfo=other).derive(z)


def main(keydir: Path, out: Path) -> None:
    keys = {
        "x25519_a": OKPKey.import_key((keydir / "x25519_a.pem").read_bytes()),
        "x25519_b": OKPKey.import_key((keydir / "x25519_b.pem").read_bytes()),
        "p256": ECKey.import_key((keydir / "p256.pem").read_bytes()),
    }

    cases = [
        # (name, key, alg, enc, extra protected header)
        ("x25519_dir_a256gcm", "x25519_a", "ECDH-ES", "A256GCM", {}),
        ("x25519_dir_a256gcm_apu_apv", "x25519_a", "ECDH-ES", "A256GCM",
         {"apu": b64u(b"Alice"), "apv": b64u(b"Bob")}),
        ("x25519_dir_a128gcm", "x25519_b", "ECDH-ES", "A128GCM", {}),
        ("x25519_a256kw_a256gcm", "x25519_a", "ECDH-ES+A256KW", "A256GCM", {}),
        ("x25519_a128kw_a128gcm_apu_apv", "x25519_b", "ECDH-ES+A128KW", "A128GCM",
         {"apu": b64u(b"sdk-client"), "apv": b64u(b"vgs-route")}),
        ("x25519_a192kw_a256gcm", "x25519_a", "ECDH-ES+A192KW", "A256GCM", {}),
        ("p256_dir_a256gcm", "p256", "ECDH-ES", "A256GCM", {}),
        ("p256_a256kw_a256gcm", "p256", "ECDH-ES+A256KW", "A256GCM", {}),
    ]

    lines = []
    w = lines.append
    w("# Generated by larky/src/test/tools/x25519_ecdh_es/gen_jwe_fixtures.py; do not edit.")
    w("#")
    w("# Reference implementation: joserfc %s (cryptography %s), Python %s."
      % (version("joserfc"), version("cryptography"), sys.version.split()[0]))
    w("# Keys: larky/src/test/tools/x25519_ecdh_es/keys (OpenSSL, test-only).")
    w("")
    w("PLAINTEXT = %r" % PLAINTEXT)
    w("")
    w("KEYS = {")
    for name in keys:
        w("    %r: {" % name)
        w("        # https://verygoodsecurity.atlassian.net/browse/SI-203")
        w("        # nosemgrep: secrets.misc.generic_private_key.generic_private_key")
        w("        \"private_pem\": %r," % (keydir / ("%s.pem" % name)).read_text())
        w("        \"public_pem\": %r," % (keydir / ("%s.pub.pem" % name)).read_text())
        w("        \"jwk\": %s," % json.dumps(keys[name].as_dict(private=True), sort_keys=True))
        w("    },")
    w("}")
    w("")
    w("# (name, key name, alg, enc, compact JWE made by joserfc)")
    w("TOKENS = [")
    for name, key_name, alg, enc, extra in cases:
        header = {"alg": alg, "enc": enc}
        header.update(extra)
        token = jwe.encrypt_compact(header, PLAINTEXT, keys[key_name], registry=REGISTRY)
        # Self-check with the reference implementation.
        assert jwe.decrypt_compact(token, keys[key_name], registry=REGISTRY).plaintext == PLAINTEXT
        w("    (%r, %r, %r, %r," % (name, key_name, alg, enc))
        w("     %r)," % token)
    w("]")
    w("")

    # RFC 8037, Appendix A.6: Bob's key is RFC 7748, Section 6.1's.
    eph = X25519PrivateKey.from_private_bytes(bytes.fromhex(
        "77076d0a7318a57d3c16c17251b26645df4c2f87ebc0992ab177fba51db92c2a"))
    bob_pub = X25519PublicKey.from_public_bytes(bytes.fromhex(
        "de9edb7d7b7dc1b4d35b61c2ece435373f8343c85b78674dadfc7e146f882b4f"))
    z = eph.exchange(bob_pub)
    assert z.hex() == "4a5d9d5ba4ce2de1728e3bf480350f25e07e21c947d19e3376f09b3c1e161742"
    # A.6's header is {"alg":"ECDH-ES+A128KW", "enc":"A128GCM", ...}, no apu/apv:
    # the KEK is 128 bits and AlgorithmID is the alg.
    kek = concat_kdf(z, "ECDH-ES+A128KW", b"", b"", 128)
    w("# RFC 8037, Appendix A.6: Concat KDF over its Z for alg ECDH-ES+A128KW")
    w("# (no apu/apv). The RFC stops at Z; this KEK is computed by")
    w("# cryptography's ConcatKDFHash.")
    w("RFC8037_A6_KEK_HEX = %r" % kek.hex())
    # RFC 7518, Appendix C, checked against the RFC's printed value.
    z_c = bytes([158, 86, 217, 29, 129, 113, 53, 211, 114, 131, 66, 131, 191, 132,
                 38, 156, 251, 49, 110, 163, 218, 128, 106, 72, 246, 218, 167, 121,
                 140, 254, 144, 196])
    assert b64u(concat_kdf(z_c, "A128GCM", b"Alice", b"Bob", 128)) == "VqqN6vgjbSBcIijNcacQGg"
    w("")
    out.write_text("\n".join(lines))


if __name__ == "__main__":
    main(Path(sys.argv[1]), Path(sys.argv[2]))
