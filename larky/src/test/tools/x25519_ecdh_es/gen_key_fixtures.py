"""Generate vendor_tests/Crypto/PublicKey/x25519_key_fixtures.star from keys/.

Run from the repository root:

    uv run --no-project --with cryptography==50.0.2 python -I \
        larky/src/test/tools/x25519_ecdh_es/gen_key_fixtures.py \
        larky/src/test/tools/x25519_ecdh_es/keys \
        larky/src/test/resources/vendor_tests/Crypto/PublicKey/x25519_key_fixtures.star

The PEM and DER encodings are OpenSSL's (make_keys.sh); the raw 32-byte keys
are read from them with `cryptography`.
"""
import sys
from importlib.metadata import version
from pathlib import Path

from cryptography.hazmat.primitives import serialization as s


def main(keydir: Path, out: Path) -> None:
    lines = [
        "# Generated by larky/src/test/tools/x25519_ecdh_es/gen_key_fixtures.py; do not edit.",
        "#",
        "# X25519 keys made by `openssl genpkey -algorithm X25519` (make_keys.sh; test-only).",
        "# Raw keys extracted with cryptography %s." % version("cryptography"),
        "",
        "OPENSSL_X25519_KEYS = [",
    ]
    for name in ("x25519_a", "x25519_b"):
        pem = (keydir / ("%s.pem" % name)).read_bytes()
        der = (keydir / ("%s.der" % name)).read_bytes()
        pub_pem = (keydir / ("%s.pub.pem" % name)).read_bytes()
        pub_der = (keydir / ("%s.pub.der" % name)).read_bytes()
        key = s.load_pem_private_key(pem, None)
        assert s.load_der_private_key(der, None).private_bytes_raw() == key.private_bytes_raw()
        raw_priv = key.private_bytes_raw()
        raw_pub = key.public_key().public_bytes_raw()
        assert s.load_pem_public_key(pub_pem).public_bytes_raw() == raw_pub
        assert s.load_der_public_key(pub_der).public_bytes_raw() == raw_pub
        lines += [
            "    {",
            "        \"name\": %r," % name,
            "        # https://verygoodsecurity.atlassian.net/browse/SI-203",
            "        # nosemgrep: secrets.misc.generic_private_key.generic_private_key",
            "        \"private_pem\": %r," % pem.decode(),
            "        \"private_der_hex\": %r," % der.hex(),
            "        \"public_pem\": %r," % pub_pem.decode(),
            "        \"public_der_hex\": %r," % pub_der.hex(),
            "        \"raw_private_hex\": %r," % raw_priv.hex(),
            "        \"raw_public_hex\": %r," % raw_pub.hex(),
            "    },",
        ]
    lines += ["]", ""]
    out.write_text("\n".join(lines))


if __name__ == "__main__":
    main(Path(sys.argv[1]), Path(sys.argv[2]))
