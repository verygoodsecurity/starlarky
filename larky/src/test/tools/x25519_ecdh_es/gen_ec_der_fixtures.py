"""Generate vendor_tests/Crypto/PublicKey/ec_der_fixtures.star from keys/p256.pem.

Run from the repository root:

    uv run --no-project --with cryptography==50.0.2 python -I \
        larky/src/test/tools/x25519_ecdh_es/gen_ec_der_fixtures.py \
        larky/src/test/tools/x25519_ecdh_es/keys/p256.pem \
        larky/src/test/resources/vendor_tests/Crypto/PublicKey/ec_der_fixtures.star

Each fixture is the P-256 key of keys/p256.pem as an RFC 5915 ECPrivateKey,
alone (SEC1) or inside PKCS#8, with the optional 'parameters' and
'publicKey' fields present, absent or wrong. They are assembled here
because OpenSSL does not write most of these combinations; the ones
`cryptography` can load are checked against the original key.
"""
import sys
from importlib.metadata import version
from pathlib import Path

from cryptography.hazmat.primitives import serialization as s
from cryptography.hazmat.primitives.asymmetric import ec

OID_EC_PUBLIC_KEY = bytes.fromhex("06072a8648ce3d0201")
OID_P256 = bytes.fromhex("06082a8648ce3d030107")
OID_P384 = bytes.fromhex("06052b81040022")


def tlv(tag: int, body: bytes) -> bytes:
    n = len(body)
    if n < 0x80:
        length = bytes([n])
    else:
        raw = n.to_bytes((n.bit_length() + 7) // 8, "big")
        length = bytes([0x80 | len(raw)]) + raw
    return bytes([tag]) + length + body


def seq(*items: bytes) -> bytes:
    return tlv(0x30, b"".join(items))


def ec_private_key(d: bytes, params: bytes = None, point: bytes = None) -> bytes:
    """RFC 5915 ECPrivateKey with the optional fields given."""
    items = [bytes.fromhex("020101"), tlv(0x04, d)]
    if params is not None:
        items.append(tlv(0xA0, params))
    if point is not None:
        items.append(tlv(0xA1, tlv(0x03, b"\x00" + point)))
    return seq(*items)


def pkcs8(inner: bytes) -> bytes:
    return seq(bytes.fromhex("020100"), seq(OID_EC_PUBLIC_KEY, OID_P256), tlv(0x04, inner))


def main(pem_path: Path, out: Path) -> None:
    key = s.load_pem_private_key(pem_path.read_bytes(), None)
    assert isinstance(key.curve, ec.SECP256R1)
    numbers = key.private_numbers()
    d = numbers.private_value.to_bytes(32, "big")
    point = key.public_key().public_bytes(s.Encoding.X962, s.PublicFormat.UncompressedPoint)
    # 0x04 followed by a valid-length X and Y that are not on P-256.
    off_curve = b"\x04" + b"\x01" * 64
    assert off_curve != point

    fixtures = [
        ("sec1_no_public", ec_private_key(d, params=OID_P256), True),
        ("pkcs8_no_params_no_public", pkcs8(ec_private_key(d)), True),
        ("pkcs8_curve_mismatch", pkcs8(ec_private_key(d, params=OID_P384, point=point)), False),
        ("sec1_off_curve_public", ec_private_key(d, params=OID_P256, point=off_curve), False),
    ]
    for name, der, loadable in fixtures:
        if loadable:
            loaded = s.load_der_private_key(der, None)
            assert loaded.private_numbers() == numbers, name

    lines = [
        "# Generated by larky/src/test/tools/x25519_ecdh_es/gen_ec_der_fixtures.py; do not edit.",
        "#",
        "# The P-256 test key of keys/p256.pem as RFC 5915 ECPrivateKey variants (test-only).",
        "# Checked with cryptography %s where it can load them." % version("cryptography"),
        "",
        "P256_D_HEX = %r" % d.hex(),
        "P256_POINT_HEX = %r" % point.hex(),
        "",
        "EC_DER_FIXTURES = {",
    ]
    for name, der, _ in fixtures:
        lines.append("    %r: %r," % (name, der.hex()))
    lines += ["}", ""]
    out.write_text("\n".join(lines))


if __name__ == "__main__":
    main(Path(sys.argv[1]), Path(sys.argv[2]))
