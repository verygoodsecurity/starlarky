"""Decrypt JWEs made by Larky with a reference JOSE library.

larky_tokens.json holds JWEs that Larky's jose.jwe.encrypt produced (to the
public keys in keys/), as [name, key name, alg, enc, token] rows. They were
made by running, in Larky (VendorLibTests), a script that calls

    jwe.encrypt(PLAINTEXT, KEYS[key]["public_pem"], encryption=enc,
                algorithm=alg, extra_headers=extra)

for each row and prints the rows as JSON. Run from the repository root:

    uv run --no-project --with joserfc==1.7.5 python -I \
        larky/src/test/tools/x25519_ecdh_es/check_larky_tokens.py \
        larky/src/test/tools/x25519_ecdh_es/keys \
        larky/src/test/tools/x25519_ecdh_es/larky_tokens.json \
        larky/src/test/resources/vendor_tests/jose/ecdh_es_larky_tokens.star \
        >| larky/src/test/tools/x25519_ecdh_es/check_larky_tokens.out

It fails unless joserfc decrypts every token to PLAINTEXT, prints one line per
token, and writes the tokens as a Larky fixture so test_jwe_ecdh_es.star
keeps decrypting them.
"""
import base64
import json
import sys
from importlib.metadata import version
from pathlib import Path

from joserfc import jwe
from joserfc.jwe import JWERegistry
from joserfc.jwk import ECKey, OKPKey

PLAINTEXT = b'{"card":"4111111111111111","exp":"12/30","cvv":"123"}'
REGISTRY = JWERegistry(algorithms=[
    "ECDH-ES", "ECDH-ES+A128KW", "ECDH-ES+A192KW", "ECDH-ES+A256KW",
    "A128GCM", "A192GCM", "A256GCM"])


def main(keydir: Path, tokens_json: Path, out_star: Path) -> None:
    keys = {
        "x25519_a": OKPKey.import_key((keydir / "x25519_a.pem").read_bytes()),
        "x25519_b": OKPKey.import_key((keydir / "x25519_b.pem").read_bytes()),
        "p256": ECKey.import_key((keydir / "p256.pem").read_bytes()),
    }
    rows = json.loads(tokens_json.read_text())
    print("joserfc %s (cryptography %s), Python %s"
          % (version("joserfc"), version("cryptography"), sys.version.split()[0]))
    for name, key_name, alg, enc, token in rows:
        obj = jwe.decrypt_compact(token, keys[key_name], registry=REGISTRY)
        header = obj.protected
        assert header["alg"] == alg and header["enc"] == enc, name
        assert obj.plaintext == PLAINTEXT, name
        epk = header["epk"]
        print("%-36s alg=%-15s enc=%s epk=%s/%s apu=%s apv=%s -> plaintext OK"
              % (name, alg, enc, epk["kty"], epk["crv"],
                 header.get("apu", "-"), header.get("apv", "-")))
    print("%d of %d Larky tokens decrypted" % (len(rows), len(rows)))

    lines = [
        "# Generated by larky/src/test/tools/x25519_ecdh_es/check_larky_tokens.py; do not edit.",
        "#",
        "# JWEs made by Larky's jose.jwe.encrypt and decrypted by joserfc %s"
        % version("joserfc"),
        "# (see check_larky_tokens.out). (name, key name, alg, enc, token)",
        "",
        "LARKY_TOKENS = [",
    ]
    for row in rows:
        lines.append("    (%r, %r, %r, %r," % tuple(row[:4]))
        lines.append("     %r)," % row[4])
    lines += ["]", ""]
    out_star.write_text("\n".join(lines))


if __name__ == "__main__":
    main(Path(sys.argv[1]), Path(sys.argv[2]), Path(sys.argv[3]))
